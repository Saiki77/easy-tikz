import esbuild from "esbuild";
import process from "process";
import { builtinModules as builtins } from "node:module";
import fs from "node:fs";
import { buildCss } from "./scripts/build-css.mjs";


const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === 'production');

// Dev mode: styles.css is rebuilt whenever a stylesheet under src/ or src/ui/ changes.
if (!prod) {
	buildCss();
	let cssTimer = null;
	const onCss = (_event, file) => {
		if (file && !String(file).endsWith('.css')) return;
		if (cssTimer) clearTimeout(cssTimer);
		cssTimer = setTimeout(() => {
			cssTimer = null;
			try {
				buildCss();
			} catch (e) {
				console.error('styles.css:', e instanceof Error ? e.message : e);
			}
		}, 50);
	};
	for (const dir of ['src', 'src/ui']) fs.watch(dir, onCss);
}

esbuild.build({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/closebrackets',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/comment',
		'@codemirror/fold',
		'@codemirror/gutter',
		'@codemirror/highlight',
		'@codemirror/history',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/matchbrackets',
		'@codemirror/panel',
		'@codemirror/rangeset',
		'@codemirror/rectangular-selection',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/stream-parser',
		'@codemirror/text',
		'@codemirror/tooltip',
		'@codemirror/view',
		...builtins],
	format: 'cjs',
	watch: !prod,
	target: 'es2016',
	logLevel: "info",
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	loader: { '.md': 'text' },
	outfile: 'main.js',
}).catch(() => process.exit(1));