/** Run a capture, once more after a failure (with a new Obsidian when the connection is gone). `fn` is told whether it is the first try. */
async function attempt(label, fn) {
    for (let round = 1; round <= 2; round++) {
        // Without the app there is nothing to retry: a failed start ends the capture.
        if (!obs) await startObsidian();
        try {
            obs.clearErrors();
            await resetInput();
            await fn(round === 1);
            return null;
        } catch (e) {
            const message = e && e.message ? e.message : String(e);
            say(`${label}: ${round === 1 ? 'failed, trying once more' : 'failed again'}: ${message}`);
            if (round === 2) return message;
            const dead = !obs || obs.cdp.closed || !(await obs.call(() => true).catch(() => false));
            if (dead) await stopObsidian();
            else await resetInput().catch(() => {});
        }
    }
    return null;
}

/**
 * Take the pictures of the selected guides. Returns a list of results:
 *   { guide, kind: 'card' | 'step', index, file, ok, error, notes, bytes, width, height }
 */
async function captureAll(guides) {
    const results = [];
    fs.mkdirSync(imgDir, { recursive: true });
    for (const guide of guides) {
        const steps = stepsOf(guide);
        const jobs = [];
        if (!onlySteps) jobs.push({ kind: 'card', index: -1, name: cardImage(guide) });
        steps.forEach((step, index) => {
            if (onlySteps && !onlySteps.includes(index + 1)) return;
            if (frameOf(step) !== 'none') jobs.push({ kind: 'step', index, name: stepImage(guide, index) });
        });
        for (const job of jobs) {
            const label = job.kind === 'card' ? `${guide.id} card` : `${guide.id} step ${job.index + 1}`;
            const raw = path.join(rawDir, job.name);
            const notes = [];
            const result = { guide: guide.id, kind: job.kind, index: job.index, file: job.name, ok: false, error: null, notes, bytes: 0, width: 0, height: 0 };
            results.push(result);
            const step = job.kind === 'step' ? steps[job.index] : null;
            const shot = (step && step.shot) || {};
            const frame = step ? frameOf(step) : 'card';
            if (step && step.shot && step.shot.frame !== undefined && !FRAMES.includes(step.shot.frame)) notes.push(`shot.frame ${fmt(step.shot.frame)} is not a frame; the editor is shown`);
            result.error = await attempt(label, async (firstTry) => {
                notes.length = 0;
                fs.rmSync(raw, { force: true });
                if (job.kind === 'card') await shootCard({ guide, raw, notes });
                else if (frame === 'note') await shootNote({ guide, index: job.index, chart: chartOfStep(guide, job.index), shot, raw, notes, firstTry });
                else await shootEditor({ chart: chartForShot(guide, job.index, shot), shot, frame, raw, notes, firstTry });
                for (const e of obs.errors) notes.push(`console ${e.type}: ${e.text.split('\n')[0]}`);
            });
            if (result.error || !fs.existsSync(raw)) {
                result.error = result.error || 'no picture was written';
                continue;
            }
            const out = path.join(imgDir, job.name);
            let saved = null;
            try {
                saved = job.kind === 'card' ? await saveCard(raw, out) : await savePicture(raw, out, frame === 'editor' ? { width: EDITOR_WIDTH, minWidth: EDITOR_MIN_WIDTH } : { width: OTHER_MAX_WIDTH });
            } catch (e) {
                fs.rmSync(`${out}.tmp.png`, { force: true });
                result.error = `the capture could not be saved: ${String(e && e.message ? e.message : e).split('\n')[0]}`;
                say(`${label}: ${result.error}`);
                continue;
            }
            Object.assign(result, saved, { ok: true });
            if (!args['keep-raw']) fs.rmSync(raw, { force: true });
            say(`${label}: ${saved.width} x ${saved.height}, ${Math.round(saved.bytes / 1024)} KB, ${saved.state === 'kept' ? 'same picture as before, file kept' : saved.state}${notes.length ? `  (${notes.length} note${notes.length === 1 ? '' : 's'})` : ''}`);
        }
    }
    return results;
}

