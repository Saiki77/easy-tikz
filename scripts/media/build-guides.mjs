/** Remove generated pages and pictures no guide uses any more. Only files this script made are touched. */
function removeStale() {
    const removed = [];
    const pages = new Set(ALL_GUIDES.map((g) => `${g.id}.md`).concat(['README.md']));
    for (const name of fs.readdirSync(outDir)) {
        if (!name.endsWith('.md') || pages.has(name)) continue;
        const file = path.join(outDir, name);
        if (fs.readFileSync(file, 'utf8').startsWith(`<!-- ${HEADER} -->`)) {
            fs.rmSync(file);
            removed.push(name);
        }
    }
    const pictures = new Set();
    for (const guide of ALL_GUIDES) {
        pictures.add(cardImage(guide));
        stepsOf(guide).forEach((step, index) => {
            if (frameOf(step) !== 'none') pictures.add(stepImage(guide, index));
        });
    }
    if (fs.existsSync(imgDir)) {
        for (const name of fs.readdirSync(imgDir)) {
            if (pictures.has(name) || !/^[a-z0-9-]+-(\d+|card)\.png$/.test(name)) continue;
            fs.rmSync(path.join(imgDir, name));
            removed.push(relImage(name));
        }
    }
    return removed;
}

