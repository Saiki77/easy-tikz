/**
 * Expand the cards of `names` (function, tool, 'label:<n>') and scroll the
 * Sliders dock to slider names. Returns the names nothing answers to.
 */
async function revealAll(names) {
    const missing = await obs.call((list) => {
        const M = window.__etzMedia;
        const m = M.requireEditor();
        const cards = [];
        const notFound = [];
        for (const name of list) {
            if (m.build && m.build.reveal(name)) {
                // reveal() focuses a field (or the header) of the card: that is how the card element is found.
                const active = document.activeElement;
                const card = active && active.closest ? active.closest('.etz-card') : null;
                if (card) cards.push(card);
                if (active && active !== document.body && typeof active.blur === 'function') active.blur();
                continue;
            }
            const input = M.sliderInput(name, 'editor', 0);
            if (input) input.scrollIntoView({ block: 'nearest' });
            else notFound.push(name);
        }
        window.__etzGuideCards = cards;
        return notFound;
    }, names);
    await obs.waitForRender();
    // Cards open with a transition; place them once they have their final height.
    await obs.call(() => {
        const cards = (window.__etzGuideCards || []).filter((c) => c.isConnected);
        window.__etzGuideCards = null;
        if (!cards.length) return;
        let scroller = null;
        for (let p = cards[0].parentElement; p; p = p.parentElement) {
            const overflow = getComputedStyle(p).overflowY;
            if ((overflow === 'auto' || overflow === 'scroll') && p.scrollHeight > p.clientHeight + 1) {
                scroller = p;
                break;
            }
        }
        if (!scroller) return;
        const margin = 12;
        const box = scroller.getBoundingClientRect();
        const rects = cards.map((c) => c.getBoundingClientRect());
        const top = Math.min(...rects.map((r) => r.top));
        const bottom = Math.max(...rects.map((r) => r.bottom));
        const last = rects[rects.length - 1];
        if (bottom - top + 2 * margin <= box.height) {
            // All of them fit: move as little as needed.
            if (top < box.top + margin) scroller.scrollTop -= box.top + margin - top;
            else if (bottom > box.bottom - margin) scroller.scrollTop += bottom - (box.bottom - margin);
        } else if (last.height + 2 * margin <= box.height) {
            // The card named last is the one the step is about: all of it, and what fits of the others above.
            scroller.scrollTop += last.bottom - (box.bottom - margin);
        } else {
            scroller.scrollTop += last.top - (box.top + margin);
        }
    });
    await obs.frames(2);
    return missing;
}

/** Focus a registered field (same ids as SceneIssue.field; source 'chart' for the Chart tab). */
function focusField(source, field) {
    return obs.call(
        (src, id) => {
            const m = window.__etzMedia.requireEditor();
            const handle = Array.from(m.fields || []).find((f) => f.source === src && f.field === id);
            if (handle) {
                handle.focus();
                return true;
            }
            return !!(m.build && m.build.reveal(src, id) && document.activeElement && document.activeElement !== document.body);
        },
        String(source),
        String(field)
    );
}

const fmt = (value) => JSON.stringify(value);

/** Something visible in the editor right now: the hover tip, the pivot mark, the ghost of a drag, the Undo bar, a menu. */
function editorShows(what) {
    return obs.call((kind) => {
        const M = window.__etzMedia;
        const m = M.requireEditor();
        if (kind === 'menu') return Array.from(document.querySelectorAll('.menu')).some(M.visible);
        if (kind === 'ghost') return !!m.modalEl.querySelector('.etz-drag-ghost > *');
        if (kind === 'undo') return M.visible(m.modalEl.querySelector('.etz-undo'));
        if (kind === 'pivot') return !!m.modalEl.querySelector('.etz-drag-pivot > *');
        const hint = m.modalEl.querySelector('.etz-drag-hint');
        return !!hint && !hint.classList.contains('tikz-hidden') && (hint.textContent || '').trim() !== '';
    }, what);
}

/**
 * One scripted gesture of a step in the editor. Problems are noted, never
 * thrown: the picture is still taken. `checks` collects what must still be
 * on screen when the picture is taken (see stillThere).
 */
async function editorAction(action, notes, checks) {
    if (!action || typeof action !== 'object') {
        notes.push(`action ${fmt(action)} is not an object`);
        return;
    }
    try {
        if (Array.isArray(action.hover)) {
            const tip = await obs.hover(action.hover);
            if (!tip) notes.push(`hover ${fmt(action.hover)}: no hover tip showed (nothing draggable at that point)`);
            else checks.push(['tip', `the hover tip of hover ${fmt(action.hover)}`]);
            if (tip && action.shift) {
                heldKeys.add('Shift');
                await obs.keyDown('Shift');
                // The editor learns about Shift from key events while the focus is inside it, and from the
                // pointer otherwise. Revealing a card left the focus outside, so move the pointer a pixel
                // and back, as a resting hand does.
                const at = await obs.point(action.hover);
                await obs.mouse.move({ x: at.x + 1, y: at.y });
                await obs.mouse.move(at);
                const shown = await obs
                    .waitFor(
                        () =>
                            obs.call((before) => {
                                const m = window.__etzMedia.requireEditor();
                                const hint = m.modalEl.querySelector('.etz-drag-hint');
                                const text = hint && !hint.classList.contains('tikz-hidden') ? (hint.textContent || '').trim() : '';
                                return !!m.modalEl.querySelector('.etz-drag-pivot > *') || (text !== '' && text !== before);
                            }, tip),
                        { timeout: 2000, interval: 40 }
                    )
                    .catch(() => false);
                if (!shown) notes.push(`hover ${fmt(action.hover)} with Shift: the tip did not change and no pivot mark showed`);
                else if (await editorShows('pivot')) checks.push(['pivot', `the pivot mark of hover ${fmt(action.hover)}`]);
                await obs.frames(2);
            }
        } else if (Array.isArray(action.drag)) {
            if (action.shift) heldKeys.add('Shift');
            await obs.mouse.drag(action.drag, { shift: !!action.shift, hold: !!action.hold, steps: 18 });
            if (!action.hold) heldKeys.delete('Shift');
            await obs.waitForRender();
            if (await editorShows(action.hold ? 'ghost' : 'undo')) checks.push(action.hold ? ['ghost', `the held drag ${fmt(action.drag)}`] : ['undo', `the Undo bar after drag ${fmt(action.drag)}`]);
            else notes.push(`drag ${fmt(action.drag)}: nothing was dragged (no shape at the start point, or it cannot move)`);
        } else if (Array.isArray(action.slider)) {
            await obs.setSlider(String(action.slider[0]), Number(action.slider[1]));
            const now = await obs.sliderValue(String(action.slider[0]));
            if (Math.abs(now - Number(action.slider[1])) > 1e-9) notes.push(`slider ${fmt(action.slider)}: the slider shows ${now} (outside its range or off its step)`);
        } else if (Array.isArray(action.focus)) {
            if (!(await focusField(action.focus[0], action.focus[1]))) notes.push(`focus ${fmt(action.focus)}: no such field`);
            await obs.waitForRender();
        } else if (action.menu !== undefined) {
            const selector = action.menu === 'add' ? '.modal.tikz-modal .etz-build-add' : action.menu === 'examples' ? '.modal.tikz-modal .etz-header button[aria-label="Examples and templates"]' : null;
            if (!selector) notes.push(`menu ${fmt(action.menu)}: unknown menu (known: "add", "examples")`);
            else {
                await obs.mouse.click(selector);
                if (await obs.waitForSelector('.menu', { timeout: 3000 })) checks.push(['menu', `the menu ${fmt(action.menu)}`]);
                else notes.push(`menu ${fmt(action.menu)}: the menu did not open`);
                // The pointer rests on the button, not on a menu item.
                await obs.frames(2);
            }
        } else {
            notes.push(`action ${fmt(action)}: unknown action`);
        }
    } catch (e) {
        notes.push(`action ${fmt(action)}: ${e.message}`);
    }
}

/**
 * Right before the picture: is every gesture state still on screen? The app
 * drops a hover and ends a held drag when its window loses the pointer
 * (another app coming to the front can do that). The first time this
 * throws, so the step is tried again; the second time it is noted.
 */
async function stillThere(lost, notes, firstTry) {
    if (!lost.length) return;
    const text = `${lost.join(', ')} went away before the picture was taken`;
    if (firstTry) throw new Error(text);
    notes.push(text);
}

/** Problems a loaded chart reports itself: they would show in the picture as a chip or a red field. */
async function noteChartProblems(notes) {
    const issues = await obs.issues();
    for (const issue of issues) notes.push(`the chart reports: ${issue.source}${issue.field ? ` ${issue.field}` : ''}: ${issue.message}`);
    const chip = await obs.statusChip();
    if (chip) notes.push(`the status chip shows "${chip}"`);
}

/** The editor modal, plus an open menu when it reaches outside (client px, inside the window). */
function editorClip() {
    return obs.call(() => {
        const M = window.__etzMedia;
        const m = M.requireEditor();
        const r = m.modalEl.getBoundingClientRect();
        let [x0, y0, x1, y1] = [r.left, r.top, r.right, r.bottom];
        for (const el of Array.from(document.querySelectorAll('.menu, .suggestion-container, .etz-popover')).filter(M.visible)) {
            const b = el.getBoundingClientRect();
            const pad = 8;
            x0 = Math.min(x0, b.left - pad);
            y0 = Math.min(y0, b.top - pad);
            x1 = Math.max(x1, b.right + pad);
            y1 = Math.max(y1, b.bottom + pad);
        }
        x0 = Math.max(0, Math.round(x0));
        y0 = Math.max(0, Math.round(y0));
        x1 = Math.min(window.innerWidth, Math.round(x1));
        y1 = Math.min(window.innerHeight, Math.round(y1));
        return { x: x0, y: y0, width: x1 - x0, height: y1 - y0 };
    });
}

/** The chart picture in the editor: the SVG of a 2D chart, the square canvas of a 3D chart. */
