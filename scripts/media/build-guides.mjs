/**
 * How every picture is written: opaque, 256 colours without dithering (an
 * editor screenshot has far fewer, so nothing visible is lost and the file
 * is about a third of the true colour one), no profiles and no time stamps,
 * so a picture that did not change is the same file on every run.
 */
const PNG = ['-background', 'white', '-alpha', 'remove', '-alpha', 'off', '-dither', 'None', '-colors', '256', '-strip', '-define', 'png:compression-level=9', '-define', 'png:exclude-chunks=date,time'];

function imageSize(file) {
    const [w, h] = magick(['identify', '-format', '%w %h', file]).trim().split(/\s+/).map(Number);
    return { width: w, height: h };
}

/**
 * Save a 2x capture as a page picture: at most `width` px wide, and
 * `minWidth` px wide when the file would otherwise be over the budget.
 */
async function savePicture(raw, out, { width, minWidth = width }) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const tmp = `${out}.tmp.png`;
    const at = (w) => {
        magick([raw, '-filter', 'Lanczos', '-resize', `${w}x>`, ...PNG, `png8:${tmp}`]);
        return fs.statSync(tmp).size;
    };
    let bytes = at(width);
    if (bytes > BUDGET && minWidth < width) bytes = at(minWidth);
    // A picture that shows what the file in docs already shows leaves that file alone (lib/stable.mjs).
    const state = await installImage(tmp, out);
    return { bytes: fs.statSync(out).size, state, ...imageSize(out) };
}

/**
 * Save a capture of the preview as a card thumbnail: fitted and centred on
 * a white canvas of CARD size. The preview is a white sheet with rounded
 * corners on the grey stage; the grey in its corners is filled with white
 * first, so the sheet and the canvas are one surface.
 */
async function saveCard(raw, out) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const tmp = `${out}.tmp.png`;
    const { width, height } = imageSize(raw);
    const inner = `${CARD.width - 2 * CARD.pad}x${CARD.height - 2 * CARD.pad}`;
    const corners = [[0, 0], [width - 1, 0], [0, height - 1], [width - 1, height - 1]].flatMap(([x, y]) => ['-draw', `color ${x},${y} floodfill`]);
    magick([raw, '-alpha', 'off', '-fuzz', '3%', '-fill', 'white', ...corners, '-fuzz', '0', '-filter', 'Lanczos', '-resize', inner, '-background', 'white', '-gravity', 'center', '-extent', `${CARD.width}x${CARD.height}`, ...PNG, `png8:${tmp}`]);
    const state = await installImage(tmp, out);
    return { bytes: fs.statSync(out).size, state, ...imageSize(out) };
}

