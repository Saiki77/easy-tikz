// step, and docs/guides/README.md as the index.
//
// Single source: src/guides (the data the Help tab of the editor shows with
// live charts). For every step this script loads the step's chart into the
// real editor of an isolated Obsidian (lib/obsidian.mjs), shows the tab,
// expands the cards and performs the gestures the step's `shot` asks for,
// and saves the picture as docs/guides/img/<id>-<n>.png. Nothing is drawn
// or retouched: a picture is a crop of what the app shows at 1728 x 1117
// (2x), scaled to at most 1600 px. docs/guides/img/<id>-card.png is the
// preview of the finished chart on a white canvas of one size.
//
// Needs what lib/obsidian.mjs needs, and ImageMagick (`magick`) on the PATH.
//
//   npm run media:guides                          # everything, about 3 minutes
//   npm run media:guides -- --only regions,sliders    # pictures of these guides only (all pages are rewritten)
//   npm run media:guides -- --only regions --step 3   # one picture
//   npm run media:guides -- --no-shots            # pages only, from the pictures already in docs/guides/img
//   npm run media:guides -- --root                # the main.js in the repository root instead of a build from source
//   npm run media:guides -- --port 9352 --work /tmp/etz-guides --out /tmp/guides
//
// A step whose picture cannot be made is tried once more, then reported; its
// page keeps the previous picture when there is one and otherwise shows no
// picture. A page never links a file that does not exist. The run ends with
// a check of every generated page (links, pictures, tables, the chart block)
// and exits with code 1 when a picture failed or a check found something.
