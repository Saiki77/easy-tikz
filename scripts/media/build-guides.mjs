/** Read every generated page back and report what a reader on GitHub would trip over. */
function checkPages() {
    const problems = [];
    const pages = fs.readdirSync(outDir).filter((n) => n.endsWith('.md'));
    for (const name of pages) {
        const text = fs.readFileSync(path.join(outDir, name), 'utf8');
        const bad = (message) => problems.push(`${name}: ${message}`);
        if (!text.startsWith(`<!-- ${HEADER} -->`)) continue;
        if (text.includes(EM_DASH)) bad('contains an em dash');
        const prose = text.replace(/```[\s\S]*?```/g, '');
        for (const m of prose.matchAll(/!?\[[^\]]*\]\(([^)\s]+)\)/g)) {
            const target = m[1];
            if (/^[a-z]+:/i.test(target) || target.startsWith('#')) continue;
            if (!fs.existsSync(path.join(outDir, decodeURIComponent(target.split('#')[0])))) bad(`link to ${target}, which does not exist`);
        }
        for (const m of prose.matchAll(/<(?:img|a)\s[^>]*?(?:src|href)="([^"]+)"/g)) {
            if (/^[a-z]+:/i.test(m[1])) continue;
            if (!fs.existsSync(path.join(outDir, m[1]))) bad(`reference to ${m[1]}, which does not exist`);
        }
        // Tables: every row of a table has as many cells as its header (pipes inside cells are escaped).
        const lines = prose.split('\n');
        for (let i = 0; i < lines.length; i++) {
            if (!/^\|( ?:?-+:? ?\|)+\s*$/.test(lines[i]) || i === 0) continue;
            const cells = (line) => line.replace(/\\\|/g, '').split('|').length - 2;
            const want = cells(lines[i - 1]);
            if (cells(lines[i]) !== want) bad(`table at line ${i}: the header has ${want} cells, the rule ${cells(lines[i])}`);
            for (let j = i + 1; j < lines.length && lines[j].startsWith('|'); j++) {
                if (cells(lines[j]) !== want) bad(`table row at line ${j + 1} has ${cells(lines[j])} cells, expected ${want}`);
            }
        }
        if (name === 'README.md') continue;
        const block = /<details>\n<summary>[^\n]*<\/summary>\n\n```easy-tikz\n([\s\S]*?)\n```\n\n<\/details>/.exec(text);
        if (!block) bad('no collapsible easy-tikz block');
        const guide = byId.get(name.replace(/\.md$/, ''));
        if (block) {
            // The block reads back as the guide's finished chart, with no problem.
            const read = parseChartText(block[1]);
            if (read.problems.length) bad(`the easy-tikz block has problems: ${read.problems.map((p) => `line ${p.line}: ${p.message}`).join('; ')}`);
            else if (guide && canonical(read.data) !== canonical(guide.chart || {})) bad('the easy-tikz block is not the finished chart of the guide');
        }
        if (guide) {
            const headings = (text.match(/^## \d+\. /gm) || []).length;
            if (headings !== stepsOf(guide).length) bad(`${headings} step headings for ${stepsOf(guide).length} steps`);
        }
    }
    if (fs.existsSync(imgDir)) {
        for (const name of fs.readdirSync(imgDir).filter((n) => n.endsWith('.png'))) {
            const bytes = fs.statSync(path.join(imgDir, name)).size;
            if (bytes > BUDGET * 1.25) problems.push(`${relImage(name)}: ${Math.round(bytes / 1024)} KB, over the budget of ${Math.round(BUDGET / 1024)} KB`);
        }
    }
    return problems;
}

// ------------------------------------------------------------------ run

const selected = onlyIds ? ALL_GUIDES.filter((g) => onlyIds.includes(g.id)) : ALL_GUIDES;
const fullRun = !args['no-shots'] && !onlyIds && !onlySteps;
let results = [];
let crashed = null;

if (!args['no-shots']) {
    const pictures = selected.reduce((n, g) => n + stepsOf(g).filter((s, i) => frameOf(s) !== 'none' && (!onlySteps || onlySteps.includes(i + 1))).length + (onlySteps ? 0 : 1), 0);
    say(`${selected.length} guide${selected.length === 1 ? '' : 's'}, up to ${pictures} pictures`);
    try {
        results = await captureAll(selected);
    } catch (e) {
        crashed = e;
    } finally {
        await stopObsidian();
    }
}

const written = writePages();
const removed = fullRun && !crashed ? removeStale() : [];
const problems = checkPages();

const made = results.filter((r) => r.ok);
const failed = results.filter((r) => !r.ok);
const noted = results.filter((r) => r.notes.length);
const where = (r) => (r.kind === 'card' ? `${r.guide} card` : `${r.guide} step ${r.index + 1}`);

console.log(`\nPages: ${written.length} written to ${path.relative(process.cwd(), outDir) || '.'}`);
if (!args['no-shots']) {
    const none = selected.reduce((n, g) => n + stepsOf(g).filter((s, i) => frameOf(s) === 'none' && (!onlySteps || onlySteps.includes(i + 1))).length, 0);
    const total = made.reduce((n, r) => n + r.bytes, 0);
    console.log(`Pictures: ${made.length} made (${(total / 1024 / 1024).toFixed(1)} MB), ${failed.length} failed, ${none} step${none === 1 ? '' : 's'} without a picture by design (frame "none")`);
    const big = made.filter((r) => r.bytes > BUDGET);
    for (const r of big) console.log(`  over ${Math.round(BUDGET / 1024)} KB: ${relImage(r.file)} (${Math.round(r.bytes / 1024)} KB)`);
}
if (removed.length) console.log(`Removed (no guide uses them any more): ${removed.join(', ')}`);
if (failed.length) {
    console.log('\nPictures that could not be made:');
    for (const r of failed) console.log(`  ${where(r)}: ${r.error}${exists(r.file) ? '  (the page keeps the previous picture)' : '  (the page shows no picture)'}`);
}
if (noted.length) {
    console.log('\nNotes (the picture was taken, but may not show what the step describes):');
    for (const r of noted) for (const note of r.notes) console.log(`  ${where(r)}: ${note}`);
}
if (problems.length) {
    console.log('\nPage checks:');
    for (const p of problems) console.log(`  ${p}`);
} else {
    console.log('Page checks: links, pictures, tables and chart blocks are fine');
}
if (crashed) console.log(`\nThe capture stopped early: ${crashed && crashed.message ? crashed.message : crashed}`);
if (!args['no-shots'] && fs.existsSync(rawDir)) fs.writeFileSync(path.join(rawDir, 'report.json'), JSON.stringify({ results, problems, removed }, null, 2));

process.exit(failed.length || problems.length || crashed ? 1 : 0);
