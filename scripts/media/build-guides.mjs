/** A step in the editor: load its chart into a new editor, arrange it as `shot` says, take the picture. */
async function shootEditor({ chart, shot, frame, raw, notes, firstTry }) {
    await obs.openEditor({ chart });
    await settleMath('editor', redrawEditor);
    await noteChartProblems(notes);

    const tab = TABS.includes(shot.tab) ? shot.tab : 'build';
    if (shot.tab !== undefined && !TABS.includes(shot.tab)) notes.push(`shot.tab ${fmt(shot.tab)} is not a tab; Build is shown`);
    const reveal = Array.isArray(shot.reveal) ? shot.reveal.map(String) : [];
    if (reveal.length) {
        const missing = await revealAll(reveal);
        if (missing.length) notes.push(`reveal: nothing is named ${missing.join(', ')}`);
    }
    // Revealing a card switches to Build: show the tab the step asks for afterwards.
    if ((await obs.editorState()).tab !== tab) await obs.showTab(tab);

    const actions = Array.isArray(shot.actions) ? shot.actions : [];
    const checks = [];
    for (const action of actions) await editorAction(action, notes, checks);
    const shown = (await obs.editorState()).tab;
    if (shown !== tab) notes.push(`the actions left the ${shown} tab open, the step asks for ${tab}`);
    await obs.waitForRender();
    // A slider may have put new text into a label. A redraw would end a hover or a held drag, so only then.
    const gesture = actions.some((a) => a && (a.hover || a.drag || a.menu !== undefined));
    if (gesture) await quietMath('editor');
    else if (actions.length) await settleMath('editor', redrawEditor);
    const lost = [];
    for (const [kind, name] of checks) {
        if (!(await editorShows(kind))) lost.push(name);
    }
    await stillThere(lost, notes, firstTry);

    if (frame === 'preview') {
        // The chart picture alone. With a gesture: the stage, so the hover tip is in the picture.
        await obs.screenshot(raw, { clip: gesture ? 'stage' : await previewClip() });
    } else {
        await obs.screenshot(raw, { clip: await editorClip() });
    }
}

const noteName = (title) => String(title || 'Chart').replace(/[\\/:*?"<>|#^[\]]/g, ' ').replace(/\s+/g, ' ').trim() || 'Chart';

/**
 * A step in a note: the chart is written into a note as "Insert into note"
 * writes it, the note is shown in reading view, and the picture is the text
 * column down to the end of the chart.
 */
async function shootNote({ guide, index, chart, shot, raw, notes, firstTry }) {
    if (await obs.editorState()) await obs.closeEditor();
    // A folder per step: slider positions of a chart are remembered per note for the session.
    const name = `Guides/${guide.id}-${index + 1}/${noteName(guide.title)}`;
    await obs.writeNote(name, `${guide.summary || ''}\n\n${chartBlock(serializeChart(chart))}\n`);
    await obs.openNote(name, { mode: 'reading' });
    await settleMath('note', redrawNote);
    const charts = await obs.noteCharts();
    if (!charts.length || !charts[0].drawn) throw new Error('the chart did not render in the note');
    if (charts[0].issues) notes.push(`the chart in the note shows the problem line "${charts[0].issues}"`);

    // The controls over the chart (align buttons, width slider) are fully shown.
    const controlsShown = () =>
        obs.call(() => {
            const chartEl = window.__etzMedia.inlineCharts()[0];
            const controls = chartEl ? Array.from(chartEl.querySelectorAll('.tikz-rendered-controls')) : [];
            return controls.length > 0 && controls.every((c) => getComputedStyle(c).opacity === '1');
        });
    let hovered = false;
    for (const action of Array.isArray(shot.actions) ? shot.actions : []) {
        try {
            if (action && Array.isArray(action.slider)) {
                await obs.setSlider(String(action.slider[0]), Number(action.slider[1]), { scope: 'note' });
            } else if (action && Array.isArray(action.hover)) {
                // Over the chart its controls show. Rest left of the middle, clear of them.
                await obs.mouse.move({ selector: '.workspace-leaf.mod-active .etz-inline-box', at: [0.3, 0.45] }, { steps: 4 });
                hovered = await obs.waitFor(controlsShown, { timeout: 2000, interval: 40 }).catch(() => false);
                if (!hovered) notes.push(`hover ${fmt(action.hover)}: the controls of the chart did not show`);
            } else {
                notes.push(`action ${fmt(action)}: not possible in a note (a note takes slider and hover)`);
            }
        } catch (e) {
            notes.push(`action ${fmt(action)}: ${e.message}`);
        }
    }
    await obs.waitForRender({ settle: 220 });
    await quietMath('note');
    if (hovered && !(await controlsShown())) await stillThere(['the controls over the chart'], notes, firstTry);

    // The text column from the note's title to the end of the chart (with its slider strip), plus a margin.
    const noteClip = () =>
        obs.call(() => {
            const M = window.__etzMedia;
            const root = M.noteEl();
            const sizer = root ? Array.from(root.querySelectorAll('.markdown-preview-sizer')).find(M.visible) : null;
            if (!sizer) return null;
            const column = sizer.getBoundingClientRect();
            let top = column.bottom;
            let bottom = column.top;
            for (const el of Array.from(sizer.querySelectorAll('.inline-title, p, .etz-inline')).filter(M.visible)) {
                const r = el.getBoundingClientRect();
                top = Math.min(top, r.top);
                bottom = Math.max(bottom, r.bottom);
            }
            if (bottom <= top) return null;
            const pad = 28;
            const view = sizer.parentElement.getBoundingClientRect();
            const below = Math.round(bottom + pad - Math.min(window.innerHeight, view.bottom));
            if (below > 0 && sizer.parentElement.scrollTop === 0) {
                // The chart reaches below the window: scroll the note, then measure again.
                sizer.parentElement.scrollTop = below;
                return { scrolled: below };
            }
            const y0 = Math.max(0, view.top, top - pad);
            const y1 = Math.min(window.innerHeight, view.bottom, bottom + pad);
            const x0 = Math.max(0, column.left - pad);
            const x1 = Math.min(window.innerWidth, column.right + pad);
            return { cut: bottom + pad > y1 + 1 || top - pad < y0 - 1, x: Math.round(x0), y: Math.round(y0), width: Math.round(x1 - x0), height: Math.round(y1 - y0) };
        });
    let clip = await noteClip();
    if (clip && clip.scrolled) {
        await obs.waitForRender({ settle: 150 });
        clip = await noteClip();
    }
    if (!clip || clip.scrolled) throw new Error('the note has no visible text column');
    if (clip.cut) notes.push('the note is taller than the window: the picture does not show all of it');
    await obs.screenshot(raw, { clip: { x: clip.x, y: clip.y, width: clip.width, height: clip.height } });
}

