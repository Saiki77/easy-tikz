/** The chart a step shows: its own, otherwise the nearest earlier one, otherwise the finished chart. */
function chartOfStep(guide, index) {
    const steps = stepsOf(guide);
    for (let i = Math.min(index, steps.length - 1); i >= 0; i--) {
        if (steps[i] && steps[i].chart) return steps[i].chart;
    }
    return guide.chart || {};
}

/**
 * The chart a step's picture starts from. A step that opens a menu shows
 * the editor as the reader has it when the menu opens, which is before the
 * step's result exists: the chart of the step before, or a new, empty chart
 * for the first step.
 */
function chartForShot(guide, index, shot) {
    const opensMenu = Array.isArray(shot && shot.actions) && shot.actions.some((a) => a && typeof a === 'object' && a.menu !== undefined);
    if (!opensMenu) return chartOfStep(guide, index);
    return index > 0 ? chartOfStep(guide, index - 1) : null;
}

