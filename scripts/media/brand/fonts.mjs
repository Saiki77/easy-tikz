/* eslint-env node */
// The brand's type is real TeX type: New Computer Modern and Latin Modern,
// as TeX Live installs them. Nothing is bundled or downloaded: the files are
// found with `kpsewhich` and loaded into the templates by a generated
// stylesheet, fonts.css, that sits next to brand.css (which imports it).
//
//   import { writeFontsCss, verifyFonts } from './fonts.mjs';
//   writeFontsCss();                       // before the first render; throws when a font is missing
//   const wrong = await verifyFonts(cdp);  // after a page has loaded: [] when every text uses its TeX font
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const BRAND_DIR = path.dirname(fileURLToPath(import.meta.url));

/**
 * One row per face. `family` is the CSS name the templates use, `ps` the
 * PostScript name Chromium reports for the loaded file (verifyFonts).
 * `optional` faces refine the kit and are left out when TeX has no such file.
 */
export const FACES = [
    // Text: New Computer Modern 10. Book is the same design with slightly
    // stronger strokes, for text that ends up small on a screen (captions, small print).
    { family: 'NewCM', file: 'NewCM10-Regular.otf', weight: 400, style: 'normal', ps: 'NewCM10-Regular' },
    { family: 'NewCM', file: 'NewCM10-Italic.otf', weight: 400, style: 'italic', ps: 'NewCM10-Italic' },
    { family: 'NewCM', file: 'NewCM10-Bold.otf', weight: 700, style: 'normal', ps: 'NewCM10-Bold' },
    { family: 'NewCM', file: 'NewCM10-BoldItalic.otf', weight: 700, style: 'italic', ps: 'NewCM10-BoldItalic' },
    { family: 'NewCM Book', file: 'NewCM10-Book.otf', weight: 400, style: 'normal', ps: 'NewCM10-Book', optional: true },
    { family: 'NewCM Book', file: 'NewCM10-BookItalic.otf', weight: 400, style: 'italic', ps: 'NewCM10-BookItalic', optional: true },
    // Formulas and typed input.
    { family: 'NewCM Math', file: 'NewCMMath-Regular.otf', weight: 400, style: 'normal', ps: 'NewCMMath-Regular' },
    { family: 'NewCM Mono', file: 'NewCMMono10-Regular.otf', weight: 400, style: 'normal', ps: 'NewCMMono10-Regular' },
    // Latin Modern: the 17 pt design for display sizes, small caps for eyebrows, the demi for small headings.
    { family: 'LM Roman 17', file: 'lmroman17-regular.otf', weight: 400, style: 'normal', ps: 'LMRoman17-Regular' },
    { family: 'LM Roman Caps', file: 'lmromancaps10-regular.otf', weight: 400, style: 'normal', ps: 'LMRomanCaps10-Regular' },
    { family: 'LM Roman Demi', file: 'lmromandemi10-regular.otf', weight: 400, style: 'normal', ps: 'LMRomanDemi10-Regular' },
];

function kpsewhich(file) {
    try {
        return execFileSync('kpsewhich', [file], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || null;
    } catch (e) {
        if (e && e.code === 'ENOENT') {
            throw new Error('brand: `kpsewhich` is not on the PATH. The brand kit sets its text in the TeX fonts of a TeX Live installation (New Computer Modern, Latin Modern): install TeX Live or add its bin directory to the PATH.');
        }
        return null; // exit code 1: not found
    }
}

/** Resolve every face to its file. Throws, naming the files, when a required one is missing. */
export function resolveFonts() {
    const missing = [];
    const faces = [];
    for (const face of FACES) {
        const file = kpsewhich(face.file);
        if (file && fs.existsSync(file)) faces.push({ ...face, path: file, url: pathToFileURL(file).href });
        else if (!face.optional) missing.push(face.file);
    }
    if (missing.length) {
        throw new Error(
            `brand: TeX font${missing.length > 1 ? 's' : ''} not found by kpsewhich: ${missing.join(', ')}. ` +
                'They come with the TeX Live packages "newcomputermodern" and "lm" (tlmgr install newcomputermodern lm). Nothing is rendered with a fallback font.'
        );
    }
    return faces;
}

/** The text of fonts.css for the resolved faces. */
export function fontsCss(faces = resolveFonts()) {
    const rules = faces.map(
        (f) => `@font-face { font-family: "${f.family}"; src: url("${f.url}") format("opentype"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: block; }`
    );
    // Without the optional Book cut, its family name maps to the regular files.
    for (const style of ['normal', 'italic']) {
        if (!faces.some((f) => f.family === 'NewCM Book' && f.style === style)) {
            const regular = faces.find((f) => f.family === 'NewCM' && f.weight === 400 && f.style === style);
            rules.push(`@font-face { font-family: "NewCM Book"; src: url("${regular.url}") format("opentype"); font-weight: 400; font-style: ${style}; font-display: block; }`);
        }
    }
    return `/* Generated by scripts/media/brand/fonts.mjs from the TeX installation on this machine. Do not edit, do not commit. */\n${rules.join('\n')}\n`;
}

/** Write fonts.css next to brand.css (or into `dir`). Returns { file, faces }. */
export function writeFontsCss(dir = BRAND_DIR) {
    const faces = resolveFonts();
    const file = path.join(dir, 'fonts.css');
    const text = fontsCss(faces);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
    return { file, faces };
}

/** Platform fonts of every text node under the first match of `selector`, summed by font. */
async function platformFonts(cdp, selector) {
    await cdp.send('DOM.enable');
    await cdp.send('CSS.enable');
    // CSS.getPlatformFontsForNode answers for the direct text children of one node: ask every element that has some.
    const marked = await cdp.evaluate(`(() => {
        const root = document.querySelector(${JSON.stringify(selector)});
        if (!root) return 0;
        let n = 0;
        for (const el of [root, ...root.querySelectorAll('*')]) {
            const own = Array.from(el.childNodes).some((c) => c.nodeType === 3 && c.textContent.trim());
            if (own && !el.closest('script, style')) { el.setAttribute('data-brand-fontcheck', ''); n++; }
        }
        return n;
    })()`);
    const sum = new Map();
    if (marked) {
        const { root } = await cdp.send('DOM.getDocument', { depth: 0 });
        const { nodeIds } = await cdp.send('DOM.querySelectorAll', { nodeId: root.nodeId, selector: '[data-brand-fontcheck]' });
        for (const nodeId of nodeIds) {
            const { fonts } = await cdp.send('CSS.getPlatformFontsForNode', { nodeId });
            for (const f of fonts) {
                const key = `${f.postScriptName}|${f.isCustomFont}`;
                const have = sum.get(key);
                if (have) have.glyphCount += f.glyphCount;
                else sum.set(key, { postScriptName: f.postScriptName, familyName: f.familyName, isCustomFont: f.isCustomFont, glyphCount: f.glyphCount });
            }
        }
        await cdp.evaluate(`document.querySelectorAll('[data-brand-fontcheck]').forEach((el) => el.removeAttribute('data-brand-fontcheck'))`);
    }
    return Array.from(sum.values()).sort((a, b) => b.glyphCount - a.glyphCount);
}

/**
 * Check the loaded page: every text must be drawn with one of the brand's
 * TeX fonts, loaded from its file (not a system fallback).
 *   cdp       the client of lib/chromium.mjs (chrome.cdp)
 *   allow     PostScript names that may appear besides the brand's (default: none)
 *   selector  the part of the page to check (default 'body')
 * Returns a list of problems, empty when all is well.
 */
export async function verifyFonts(cdp, { allow = [], selector = 'body' } = {}) {
    const known = new Set(FACES.map((f) => f.ps).concat(allow));
    const fonts = await platformFonts(cdp, selector);
    const problems = [];
    for (const f of fonts) {
        if (allow.includes(f.postScriptName)) continue;
        if (!f.isCustomFont) problems.push(`${f.glyphCount} glyph(s) drawn with the system font "${f.familyName}" (${f.postScriptName}) instead of a TeX font`);
        else if (!known.has(f.postScriptName)) problems.push(`${f.glyphCount} glyph(s) drawn with an unexpected font: ${f.postScriptName}`);
    }
    if (!fonts.length) problems.push('the page draws no text at all');
    return problems;
}

/** [{ postScriptName, familyName, glyphCount, isCustomFont }] for the first match of `selector` and everything in it. */
export function fontsUsed(cdp, selector = 'body') {
    return platformFonts(cdp, selector);
}
